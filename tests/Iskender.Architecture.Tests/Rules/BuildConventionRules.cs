using System.Text.RegularExpressions;
using Iskender.Architecture.Tests.Support;

namespace Iskender.Architecture.Tests.Rules;

/// <summary>
/// Rules B1 to B6: every project takes its versions and protected settings from the root build files, and nothing
/// turns a check off without being listed.
/// </summary>
public static partial class BuildConventionRules
{
    private const string CentralManagement = "ManagePackageVersionsCentrally";

    private const string UnreadableId = "(unreadable)";

    /// <summary>Names the compiler treats as generated, which turns off nullable checks and analyzers.</summary>
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];

    private static readonly string[] GeneratedMarkers = ["<auto-generated", "<autogenerated"];

    private static readonly string[] SuppressionSettings = ["NoWarn", "WarningsNotAsErrors"];

    /// <summary>Files that change settings from outside a project file, allowed only at the repository root.</summary>
    private static readonly string[] RootOnlyFiles =
    [
        RepositoryScan.RootBuildProps,
        RepositoryScan.RootBuildTargets,
        RepositoryScan.RootPackagesProps,
        ".editorconfig",
    ];

    /// <summary>Files that change settings from outside a project file, allowed nowhere.</summary>
    private static readonly string[] ForbiddenFiles = ["Directory.Build.rsp", "MSBuild.rsp", ".globalconfig"];

    /// <summary>The file types MSBuild imports from a project's <c>obj/</c>, each as <c>&lt;project file&gt;.*.&lt;type&gt;</c>.</summary>
    private static readonly string[] ProjectExtensionTypes = ["props", "targets"];

    /// <summary>What NuGet's restore writes to <c>obj/</c>, and overwrites on every restore.</summary>
    private static readonly string[] NuGetGeneratedSuffixes = [".nuget.g.props", ".nuget.g.targets"];

    public static IEnumerable<Violation> Evaluate(RuleContext context) =>
        CentralVersions(context)
            .Concat(LockFiles(context))
            .Concat(RequiredSettings(context))
            .Concat(ProtectedSettings(context))
            .Concat(ConfigurationFiles(context))
            .Concat(ProjectExtensionFiles(context))
            .Concat(NullableChecks(context))
            .Concat(BuildFileSuppressions(context))
            .Concat(SourceSuppressions(context))
            .Concat(EditorConfigSuppressions(context));

    private static string SourceOf(ScannedProject project, string definedIn) =>
        string.Equals(definedIn, project.Path, StringComparison.Ordinal) ? project.Name : definedIn;

    private static IEnumerable<Violation> CentralVersions(RuleContext context)
    {
        var source = context.Source;

        foreach (var project in context.Scan.Projects)
        {
            foreach (var package in project.PackageReferences)
            {
                var isCentral = string.Equals(package.Type, "GlobalPackageReference", StringComparison.OrdinalIgnoreCase)
                    && string.Equals(package.DefinedIn, RepositoryScan.RootPackagesProps, StringComparison.Ordinal);

                if (!isCentral && package.Metadata.ContainsKey("Version"))
                {
                    yield return source.Violate("B1", SourceOf(project, package.DefinedIn), package.Value, "states a package version outside central management");
                }

                if (package.Metadata.ContainsKey("VersionOverride"))
                {
                    yield return source.Violate("B1", SourceOf(project, package.DefinedIn), package.Value, "states a version override");
                }
            }

            foreach (var property in project.Properties.Where(property => string.Equals(property.Name, CentralManagement, StringComparison.OrdinalIgnoreCase)))
            {
                yield return source.Violate("B1", SourceOf(project, property.DefinedIn), CentralManagement, "a project must not set central package management");
            }

            // Whatever its operation: an Update in a project changes the version that central management resolves.
            var versions = project.Items.Where(item =>
                string.Equals(item.Type, "PackageVersion", StringComparison.OrdinalIgnoreCase)
                && !string.Equals(item.DefinedIn, RepositoryScan.RootPackagesProps, StringComparison.Ordinal));

            foreach (var version in versions)
            {
                foreach (var package in version.Value.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                {
                    yield return source.Violate("B1", SourceOf(project, version.DefinedIn), package, $"a PackageVersion item may appear only in the root {RepositoryScan.RootPackagesProps}");
                }
            }
        }
    }

    private static IEnumerable<Violation> LockFiles(RuleContext context)
    {
        foreach (var project in context.Scan.Projects.Where(project => !project.HasLockFile))
        {
            yield return context.Source.Violate("B2", project.Name, "packages.lock.json", "has no committed lock file");
        }
    }

    private static IEnumerable<Violation> RequiredSettings(RuleContext context)
    {
        var source = context.Source;

        foreach (var setting in source.ProtectedSettings.Required)
        {
            var file = context.Scan.RootFiles.FirstOrDefault(root => string.Equals(root.Name, setting.File, StringComparison.Ordinal));
            var found = file?.Properties.Where(property => string.Equals(property.Name, setting.Name, StringComparison.OrdinalIgnoreCase)).ToList() ?? [];

            if (found.Count == 0)
            {
                yield return source.Violate("B3", setting.File, setting.Name, $"must be set to {setting.Value}, but is not set");
                continue;
            }

            if (found.Count > 1)
            {
                yield return source.Violate("B3", setting.File, $"{setting.Name} (count)", "must be set exactly once");
            }

            if (found.Any(property => property.IsConditional || property.InTarget))
            {
                yield return source.Violate("B3", setting.File, $"{setting.Name} (condition)", "must be set with no condition and outside any target");
            }

            foreach (var property in found.Where(property => !string.Equals(property.Value, setting.Value, StringComparison.Ordinal)))
            {
                yield return source.Violate("B3", setting.File, setting.Name, $"must be {setting.Value}, but is '{property.Value}'");
            }
        }
    }

    private static IEnumerable<Violation> ProtectedSettings(RuleContext context)
    {
        var source = context.Source;
        var settings = source.ProtectedSettings;

        foreach (var project in context.Scan.Projects)
        {
            foreach (var property in project.Properties)
            {
                if (settings.Required.Any(setting => string.Equals(setting.Name, property.Name, StringComparison.OrdinalIgnoreCase)))
                {
                    yield return source.Violate("B4", SourceOf(project, property.DefinedIn), property.Name, "may be set only in its root build file");
                }

                if (settings.Forbidden.Any(entry => IsForbiddenName(entry, property.Name)))
                {
                    yield return source.Violate("B4", SourceOf(project, property.DefinedIn), property.Name, "must not be set anywhere");
                }
            }

            foreach (var item in project.Items.Where(item => settings.ForbiddenItems.Contains(item.Type, StringComparer.OrdinalIgnoreCase)))
            {
                yield return source.Violate("B4", SourceOf(project, item.DefinedIn), item.Type, "this item must not appear anywhere");
            }
        }

        // The scan leaves required settings in the root props files out of each project, so one in the wrong root file is found here.
        foreach (var file in context.Scan.RootFiles)
        {
            foreach (var property in file.Properties)
            {
                var setting = settings.Required.FirstOrDefault(entry => string.Equals(entry.Name, property.Name, StringComparison.OrdinalIgnoreCase));
                if (setting is not null && !string.Equals(setting.File, file.Name, StringComparison.Ordinal))
                {
                    yield return source.Violate("B4", file.Name, property.Name, $"may be set only in {setting.File}");
                }
            }

            foreach (var property in file.Properties.Where(property => settings.Forbidden.Any(entry => IsForbiddenName(entry, property.Name))))
            {
                yield return source.Violate("B4", file.Name, property.Name, "must not be set anywhere");
            }

            foreach (var item in file.Items.Where(item => settings.ForbiddenItems.Contains(item.Type, StringComparer.OrdinalIgnoreCase)))
            {
                yield return source.Violate("B4", file.Name, item.Type, "this item must not appear anywhere");
            }
        }
    }

    /// <summary>An entry such as <c>AnalysisMode&lt;Category&gt;</c> stands for that prefix with a category after it.</summary>
    private static bool IsForbiddenName(string entry, string name)
    {
        var placeholder = entry.IndexOf('<', StringComparison.Ordinal);
        if (placeholder < 0)
        {
            return string.Equals(entry, name, StringComparison.OrdinalIgnoreCase);
        }

        return name.Length > placeholder && name.StartsWith(entry[..placeholder], StringComparison.OrdinalIgnoreCase);
    }

    private static IEnumerable<Violation> ConfigurationFiles(RuleContext context)
    {
        foreach (var path in RepositoryPaths.EnumerateFiles(context.Root))
        {
            var name = Path.GetFileName(path);
            var relative = RepositoryPaths.Relative(context.Root, path);

            if (ForbiddenFiles.Contains(name, StringComparer.OrdinalIgnoreCase))
            {
                yield return context.Source.Violate("B4", relative, name, "this file must not exist anywhere");
            }
            else if (relative.Contains('/', StringComparison.Ordinal) && RootOnlyFiles.Contains(name, StringComparer.OrdinalIgnoreCase))
            {
                yield return context.Source.Violate("B4", relative, name, "this file may exist only at the repository root");
            }
        }
    }

    /// <summary>
    /// MSBuild imports these from <c>obj/</c>, which the scan skips, on any checkout that holds them. Only the
    /// directory directly under each project is read, because that is the one the default path points at, and
    /// the properties that move it are forbidden.
    /// </summary>
    private static IEnumerable<Violation> ProjectExtensionFiles(RuleContext context)
    {
        foreach (var project in context.Scan.Projects)
        {
            var directory = Path.Combine(context.Root, Path.GetDirectoryName(project.Path)!, "obj");
            if (!Directory.Exists(directory))
            {
                continue;
            }

            var projectFile = Path.GetFileName(project.Path);
            foreach (var path in ProjectExtensionTypes.SelectMany(type => Directory.EnumerateFiles(directory, $"{projectFile}.*.{type}")))
            {
                var name = Path.GetFileName(path);
                if (!NuGetGeneratedSuffixes.Any(suffix => string.Equals(name, projectFile + suffix, StringComparison.OrdinalIgnoreCase)))
                {
                    yield return context.Source.Violate("B4", project.Name, $"obj/{name}", "MSBuild imports this file, which the scan does not read");
                }
            }
        }
    }

    private static IEnumerable<Violation> NullableChecks(RuleContext context)
    {
        var source = context.Source;

        foreach (var file in SourceScan.Files(context.Root))
        {
            var name = Path.GetFileName(file.Path);
            if (GeneratedSuffixes.Any(suffix => name.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
                || name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
            {
                yield return source.Violate("B5", file.Path, name, "this file name is treated as generated code, which turns off nullable checks");
            }

            if (HasGeneratedMarker(file.Text))
            {
                yield return source.Violate("B5", file.Path, "generated-code comment", "a comment before the first code marks this file as generated, which turns off nullable checks");
            }

            if (file.Lines.Any(line => NullableDisable().IsMatch(line.Blanked)))
            {
                yield return source.Violate("B5", file.Path, "#nullable disable", "turns off nullable checks");
            }
        }
    }

    /// <summary>Walks the comments and directives before the first code in the original text, as the compiler does.</summary>
    private static bool HasGeneratedMarker(string text)
    {
        var index = 0;
        while (index < text.Length)
        {
            if (char.IsWhiteSpace(text[index]))
            {
                index++;
                continue;
            }

            int end;
            var isComment = true;
            if (text[index] == '#')
            {
                end = EndOfLine(text, index);
                isComment = false;
            }
            else if (string.CompareOrdinal(text, index, "//", 0, 2) == 0)
            {
                end = EndOfLine(text, index);
            }
            else if (string.CompareOrdinal(text, index, "/*", 0, 2) == 0)
            {
                var close = text.IndexOf("*/", index + 2, StringComparison.Ordinal);
                end = close < 0 ? text.Length : close + 2;
            }
            else
            {
                return false;
            }

            if (isComment)
            {
                var comment = text[index..end];
                if (GeneratedMarkers.Any(marker => comment.Contains(marker, StringComparison.OrdinalIgnoreCase)))
                {
                    return true;
                }
            }

            index = end;
        }

        return false;
    }

    private static int EndOfLine(string text, int index)
    {
        var end = text.IndexOf('\n', index);
        return end < 0 ? text.Length : end;
    }

    private static IEnumerable<Violation> BuildFileSuppressions(RuleContext context)
    {
        var properties = context.Scan.Projects.SelectMany(project => project.Properties)
            .Concat(context.Scan.RootFiles.SelectMany(file => file.Properties))
            .Where(property => SuppressionSettings.Contains(property.Name, StringComparer.OrdinalIgnoreCase))
            .Select(property => (Setting: property.Name, property.Value, property.DefinedIn));

        var items = context.Scan.Projects.SelectMany(project => project.Items)
            .Concat(context.Scan.RootFiles.SelectMany(file => file.Items))
            .SelectMany(item => item.Metadata
                .Where(metadata => SuppressionSettings.Contains(metadata.Key, StringComparer.OrdinalIgnoreCase))
                .Select(metadata => (Setting: metadata.Key, metadata.Value, item.DefinedIn)));

        foreach (var (setting, value, definedIn) in properties.Concat(items))
        {
            foreach (var id in value.Split([';', ','], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Where(id => !IsSelfReference(id)))
            {
                var violation = Unlisted(context, id, setting, definedIn);
                if (violation is not null)
                {
                    yield return violation;
                }
            }
        }
    }

    /// <summary>The usual way to append to a list, such as <c>$(NoWarn)</c>, which suppresses nothing itself.</summary>
    private static bool IsSelfReference(string id) =>
        SuppressionSettings.Any(setting =>
            string.Equals(id, $"$({setting})", StringComparison.OrdinalIgnoreCase)
            || string.Equals(id, $"%({setting})", StringComparison.OrdinalIgnoreCase));

    private static IEnumerable<Violation> SourceSuppressions(RuleContext context)
    {
        foreach (var file in SourceScan.Files(context.Root))
        {
            foreach (var alias in SourceScan.AttributeAliases(file).Where(alias => alias.Attribute != SourceScan.InternalsVisibleTo))
            {
                yield return context.Source.Violate("B6", file.Path, $"{alias.Attribute} (alias {alias.Alias})", "aliases this attribute, which hides every later use from the source scan");
            }

            foreach (var line in file.Lines)
            {
                var pragma = PragmaDisable().Match(line.Blanked);
                if (pragma.Success)
                {
                    foreach (var id in PragmaIds(pragma.Groups[1].Value))
                    {
                        var violation = Unlisted(context, id, "#pragma warning disable", file.Path);
                        if (violation is not null)
                        {
                            yield return violation;
                        }
                    }
                }

                foreach (Match attribute in SuppressionAttribute().Matches(line.Blanked))
                {
                    var name = attribute.Groups[1].Value;
                    var id = string.Equals(name, "GeneratedCode", StringComparison.Ordinal) ? name : AttributeId(line.Original, attribute.Index);
                    var violation = Unlisted(context, id, name, file.Path);
                    if (violation is not null)
                    {
                        yield return violation;
                    }
                }
            }
        }
    }

    private static string[] PragmaIds(string text)
    {
        var ids = text.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        return ids.Length == 0 ? ["(all)"] : ids;
    }

    /// <summary>The check ID is the attribute's second string, up to any colon. It is read from the original line.</summary>
    private static string AttributeId(string original, int start)
    {
        var strings = QuotedString().Matches(original, start);
        return strings.Count < 2 ? UnreadableId : strings[1].Groups[1].Value.Split(':')[0].Trim();
    }

    private static IEnumerable<Violation> EditorConfigSuppressions(RuleContext context)
    {
        var files = RepositoryPaths.EnumerateFiles(context.Root)
            .Where(path => string.Equals(Path.GetFileName(path), ".editorconfig", StringComparison.OrdinalIgnoreCase));

        foreach (var path in files)
        {
            var relative = RepositoryPaths.Relative(context.Root, path);
            foreach (var line in File.ReadLines(path))
            {
                if (GeneratedCodeOption().IsMatch(line))
                {
                    var violation = Unlisted(context, "generated_code", "generated_code", relative);
                    if (violation is not null)
                    {
                        yield return violation;
                    }
                }

                var severity = SuppressingSeverity().Match(line);
                if (severity.Success)
                {
                    var id = severity.Groups[1].Success ? severity.Groups[1].Value : severity.Groups[2].Value;
                    var violation = Unlisted(context, id, "severity", relative);
                    if (violation is not null)
                    {
                        yield return violation;
                    }
                }
            }
        }
    }

    /// <summary>A suppression is allowed only if the rule source lists that ID for that form in that file.</summary>
    private static Violation? Unlisted(RuleContext context, string id, string form, string file)
    {
        var where = $"{form} in {file}";
        var isListed = context.Source.Suppressions.Any(listed =>
            string.Equals(listed.Id, id, StringComparison.OrdinalIgnoreCase)
            && string.Equals(listed.Where, where, StringComparison.OrdinalIgnoreCase));

        return isListed ? null : context.Source.Violate("B6", file, id, $"{form} is not a listed suppression");
    }

    [GeneratedRegex(@"^\s*#\s*nullable\s+disable\b")]
    private static partial Regex NullableDisable();

    [GeneratedRegex(@"^\s*#\s*pragma\s+warning\s+disable\b(.*)$")]
    private static partial Regex PragmaDisable();

    [GeneratedRegex(@"(?<!\w)(?:[\w.:]*[.:])?(SuppressMessage|UnconditionalSuppressMessage|GeneratedCode)(?:Attribute)?\s*(?:\(|\]|,|$)")]
    private static partial Regex SuppressionAttribute();

    [GeneratedRegex("\x22([^\x22]*)\x22")]
    private static partial Regex QuotedString();

    [GeneratedRegex(@"^\s*generated_code\s*=\s*true\b", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedCodeOption();

    [GeneratedRegex(@"^\s*(?:dotnet_diagnostic\.(\S+?)|(dotnet_analyzer_diagnostic(?:\.\S+?)?))\.severity\s*=\s*(?:none|silent|suggestion|default)\b", RegexOptions.IgnoreCase)]
    private static partial Regex SuppressingSeverity();
}
